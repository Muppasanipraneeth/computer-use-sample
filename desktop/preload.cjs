const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("desktop", {
  platform: process.platform,
  getAuth: () => ipcRenderer.invoke("auth:get"),
  saveAuth: (updates) => ipcRenderer.invoke("auth:save", updates),
  loginOmp: () => ipcRenderer.invoke("auth:login"),
  health: () => ipcRenderer.invoke("runner:health"),
  scenarios: () => ipcRenderer.invoke("scenarios:list"),
  startRun: (input) => ipcRenderer.invoke("run:start", input),
  getRun: (runId) => ipcRenderer.invoke("run:get", runId),
  liveRuns: () => ipcRenderer.invoke("run:live"),
  stopRun: (runId) => ipcRenderer.invoke("run:stop", runId),
  deleteRun: (runId) => ipcRenderer.invoke("run:delete", runId),
  copyDiagnostics: () => ipcRenderer.invoke("diagnostics:copy"),
  firstShow: () => ipcRenderer.invoke("app:first-show"),
  welcomeVoice: (request) => ipcRenderer.invoke("welcome:voice", request),
  // The floating face: send-only, many times a second for the voice level.
  avatarVoice: (payload) => ipcRenderer.send("avatar:voice", payload),
  avatarTask: (task, text, outcome) => ipcRenderer.send("avatar:task", task, text, outcome),
  avatarLevel: (level, source) => ipcRenderer.send("avatar:level", level, source),
  openLogs: () => ipcRenderer.invoke("logs:open"),
  searchRuns: (query) => ipcRenderer.invoke("runs:search", query),
  answerRun: (runId, questionId, answer) => ipcRenderer.invoke("run:answer", runId, questionId, answer),
  memories: () => ipcRenderer.invoke("memory:list"),
  addMemory: (text) => ipcRenderer.invoke("memory:add", text),
  removeMemory: (id) => ipcRenderer.invoke("memory:remove", id),
  routines: () => ipcRenderer.invoke("routines:list"),
  saveRoutine: (routine) => ipcRenderer.invoke("routines:save", routine),
  removeRoutine: (id) => ipcRenderer.invoke("routines:remove", id),
  takeDueRoutines: () => ipcRenderer.invoke("routines:take-due"),
  onRoutineDue: (handler) => ipcRenderer.on("routine:due", () => handler()),
  typedUnderstand: (text) => ipcRenderer.invoke("typed:understand", text),
  onSignInWaiting: (handler) => ipcRenderer.on("browser:signin-waiting", () => handler()),
  onOpenSettings: (handler) => ipcRenderer.on("settings:open", (_event, tab) => handler(tab)),
  onAvatarPrefs: (handler) => ipcRenderer.on("avatar:prefs", (_event, prefs) => handler(prefs)),
  followUp: (request) => ipcRenderer.invoke("run:follow-up", request),
  steerRun: (runId, message, mode, attachments) => ipcRenderer.invoke("run:steer", runId, message, mode, attachments),
  pickAttachments: (kind) => ipcRenderer.invoke("attach:pick", kind),
  classifyAttachments: (paths) => ipcRenderer.invoke("attach:classify", paths),
  saveImage: (bytes, type) => ipcRenderer.invoke("attach:save-image", bytes, type),
  thumbnail: (filePath) => ipcRenderer.invoke("attach:thumbnail", filePath),
  // Dropped File objects carry no path in the page since Electron 32; only the preload can ask for it.
  pathForFile: (file) => webUtils.getPathForFile(file),
  pauseRun: (runId) => ipcRenderer.invoke("run:pause", runId),
  resumeRun: (runId) => ipcRenderer.invoke("run:resume", runId),
  stepAside: () => ipcRenderer.invoke("window:step-aside"),
  comeBack: () => ipcRenderer.invoke("window:come-back"),
  openExternal: (url) => ipcRenderer.invoke("shell:open", url),
  favicon: (host) => ipcRenderer.invoke("favicon:get", host),
  voiceEnable: () => ipcRenderer.invoke("voice:enable"),
  voiceDisable: () => ipcRenderer.invoke("voice:disable"),
  voiceAudio: (samples) => ipcRenderer.send("voice:audio", samples),
  voiceUnderstand: (request) => ipcRenderer.invoke("voice:understand", request),
  voiceSpeak: (request) => ipcRenderer.invoke("voice:speak", request),
  voiceSpeaking: (on, followUp) => ipcRenderer.send("voice:speaking", on, followUp),
  voiceSilence: (id) => ipcRenderer.send("voice:silence", id),
  voiceBusy: (busy) => ipcRenderer.send("voice:busy", busy),
  voicePrefs: (prefs) => ipcRenderer.send("voice:prefs", prefs),
  setTheme: (mode) => ipcRenderer.send("theme:set", mode),
  onVoice: (handler) => {
    for (const kind of ["state", "command", "progress", "speech"]) ipcRenderer.on(`voice:${kind}`, (_event, payload) => handler(kind, payload));
  },
  voiceList: () => ipcRenderer.invoke("voice:list"),
  getProfile: () => ipcRenderer.invoke("profile:get"),
  saveProfile: (profile) => ipcRenderer.invoke("profile:save", profile),
  browserSignIn: (url) => ipcRenderer.invoke("browser:signin", url),
  connections: () => ipcRenderer.invoke("connections:list"),
  connectApp: (slug) => ipcRenderer.invoke("connections:connect", slug),
  disconnectApp: (slug) => ipcRenderer.invoke("connections:disconnect", slug),
  permissions: () => ipcRenderer.invoke("permissions:get"),
  openPermission: (kind) => ipcRenderer.invoke("permissions:open", kind),
  relaunch: () => ipcRenderer.invoke("app:relaunch"),
});
